const {_electron}=require('playwright');
const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');const data=path.resolve(root,'../../work/smoke-'+Date.now());
const backup=path.join(data,'roundtrip.cutenote');const png=path.join(data,'drawing.png');
const env={...process.env,CUTENOTES_TEST_DATA:data};delete env.ELECTRON_RUN_AS_NODE;
let app,page;const errors=[];
async function launch(){app=await _electron.launch({...(process.env.CUTENOTES_EXECUTABLE?{executablePath:process.env.CUTENOTES_EXECUTABLE,args:[]}:{args:[root]}),env});page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error'){console.log('Renderer:',m.text().slice(0,400));errors.push(m.text());}});await page.getByRole('button',{name:'New note',exact:true}).first().waitFor({timeout:30000});}
async function snapshot(){return page.evaluate(()=>window.cute.snapshot());}
async function main(){
  await launch();
  await page.keyboard.press('Control+n');
  await page.getByLabel('Note title',{exact:true}).fill('A Sinhala test');
  await page.locator('.cm-content').fill('ආයුබෝවන්!\nprint("Saved locally")');
  await page.getByLabel('Note language',{exact:true}).selectOption('python');
  await page.keyboard.press('Control+s');
  await page.waitForFunction(async()=>{const s=await window.cute.snapshot();return s.notes.some(n=>n.title==='A Sinhala test'&&n.content.includes('ආයුබෝවන්')&&n.language==='python');});
  console.log('PASS: create, edit, Unicode, language and save');
  await page.getByRole('button',{name:'Add to favorites',exact:true}).click();
  await page.keyboard.press('Control+s');
  await page.getByLabel('New task',{exact:true}).fill('Check desktop sync');await page.getByRole('button',{name:'Add task',exact:true}).click();
  await page.getByRole('button',{name:'Complete: Check desktop sync',exact:true}).waitFor();
  const stickyPromise=app.waitForEvent('window');
  await page.getByRole('button',{name:'Pin tasks to desktop',exact:true}).click();
  const sticky=await stickyPromise;
  sticky.on('pageerror',e=>errors.push(e.message));
  await sticky.getByLabel('Sticky note',{exact:true}).fill('A desktop reminder 🌿');
  await sticky.getByRole('button',{name:'Complete: Check desktop sync',exact:true}).click();
  await page.getByRole('button',{name:'Mark incomplete: Check desktop sync',exact:true}).waitFor();
  await sticky.getByRole('button',{name:'Close window',exact:true}).click();
  await page.waitForFunction(async()=>(await window.cute.snapshot()).settings.stickyText==='A desktop reminder 🌿');
  console.log('PASS: task completion syncs between windows; sticky text saves on close');
  await page.bringToFront();await page.keyboard.press('Control+Shift+n');
  await page.getByLabel('Note title',{exact:true}).fill('Drawing test');
  const canvas=page.locator('.excalidraw__canvas.interactive');await canvas.waitFor({timeout:30000});
  await canvas.click({position:{x:150,y:180}});await page.keyboard.press('r');
  const bounds=await canvas.boundingBox();await page.mouse.move(bounds.x+150,bounds.y+180);await page.mouse.down();await page.mouse.move(bounds.x+350,bounds.y+300,{steps:10});await page.mouse.up();
  await page.keyboard.press('Control+s');
  await page.waitForFunction(async()=>{const n=(await window.cute.snapshot()).notes.find(n=>n.title==='Drawing test');return n&&JSON.parse(n.content).elements.length>0;},{timeout:15000});
  await page.keyboard.press('t');await canvas.click({position:{x:180,y:220}});await page.keyboard.insertText('Cozy ideas');await page.keyboard.press('Escape');await page.keyboard.press('Control+s');
  await app.evaluate(({dialog},target)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:target});},png);
  await page.getByRole('button',{name:'Export',exact:true}).click();
  await page.getByRole('button',{name:'PNG',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[role=status]')?.textContent.includes('Whiteboard exported'),{timeout:20000});
  assert(fs.existsSync(png));assert(fs.statSync(png).size>100);
  await page.screenshot({path:path.resolve(root,'../CuteNotes-whiteboard.png')});
  console.log('PASS: whiteboard draws, persists and exports PNG offline');
  await app.evaluate(({dialog},target)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:target});},backup);
  await page.getByRole('button',{name:'Backup',exact:true}).click();await page.getByText('Backup exported',{exact:true}).waitFor();assert(fs.existsSync(backup));
  await app.evaluate(({dialog},target)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[target]});dialog.showMessageBox=async()=>({response:1});},backup);
  await page.getByRole('button',{name:'Settings & backups',exact:true}).click();await page.getByRole('button',{name:'Import backup',exact:true}).click();await page.getByText('Backup restored',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Dark',exact:true}).click();await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark');
  await page.getByRole('button',{name:'Light',exact:true}).click();await page.getByRole('button',{name:'Close settings',exact:true}).click();
  console.log('PASS: backup export/import and appearance settings');
  const before=await snapshot();
  await page.getByRole('button',{name:'Close window',exact:true}).click();
  await new Promise(resolve=>{if(app.process().exitCode!==null)resolve();else app.process().once('exit',resolve);});
  await launch();const after=await snapshot();assert.equal(after.notes.length,before.notes.length);assert(after.notes.some(n=>n.title==='A Sinhala test'&&n.favorite===1));assert.equal(after.settings.stickyText,'A desktop reminder 🌿');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS: app restart retains notes, favorites, drawing, tasks and sticky content; no renderer exceptions');
  await app.close();
  console.log('ALL DESKTOP SMOKE TESTS PASSED');
}
main().catch(async e=>{console.error(e);if(page)try{await page.screenshot({path:path.resolve(root,'../../work/smoke-failure.png')});}catch{}if(app)try{await app.close();}catch{}process.exitCode=1;});
